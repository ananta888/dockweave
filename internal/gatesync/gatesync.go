// Package gatesync mirrors the deterministic gate connectors of the 2D graph
// into a Paperclip workspace config (`<workspace>/.paperclip/gates.json`).
//
// The graph document is user authored and lives in the web gateway; Paperclip
// only ever reads the file inside the workspace it runs in. This package is the
// bridge between the two: it derives the Paperclip gate config from the
// enabled `kind:"gate"` connectors and writes it atomically.
//
// Only connectors that actually carry executable fields (a shell command) or
// explicitly request the review/human gates produce output. A file that was
// not generated by DockWeave is never overwritten when the graph has no gates,
// so a hand-maintained gates.json stays intact.
package gatesync

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// GeneratedBy marks files owned by this package.
const GeneratedBy = "dockweave-graph"

const gatesRelPath = ".paperclip/gates.json"

// Connector is the subset of the graph connector config we care about.
type Connector struct {
	ID       string `json:"id"`
	Kind     string `json:"kind"`
	Name     string `json:"name"`
	Enabled  bool   `json:"enabled"`
	Contract string `json:"contract"`
}

// Settings is the graph document's `paperclip` block.
type Settings struct {
	Workspace string `json:"workspace"`
	SyncGates *bool  `json:"syncGates"`
}

func (s Settings) enabled() bool {
	return s.SyncGates != nil && *s.SyncGates
}

// Document is the subset of the graph document needed for derivation.
type Document struct {
	Connectors []Connector `json:"connectors"`
	Paperclip  *Settings   `json:"paperclip"`
}

// Contract is the JSON stored in Connector.Contract for gate connectors.
type Contract struct {
	Expression            string   `json:"expression"`
	OnTrue                string   `json:"on_true"`
	OnFalse               string   `json:"on_false"`
	Command               string   `json:"command"`
	Cwd                   string   `json:"cwd"`
	TimeoutSec            int      `json:"timeout_sec"`
	When                  string   `json:"when"`
	ReviewRequired        bool     `json:"review_required"`
	HumanApprovalRequired bool     `json:"human_approval_required"`
	RunnerImage           string   `json:"runner_image"`
	Protected             []string `json:"protected"`
	AllowPaths            []string `json:"allow_paths"`
	DenyNewDependencies   bool     `json:"deny_new_dependencies"`
	SecretScan            bool     `json:"secret_scan"`
	Budget                *Budget  `json:"budget"`
}

// Budget is an optional broker-backed limit checked before/after a gate run.
type Budget struct {
	GrantID        string  `json:"grant_id"`
	MaxRequestsDay int     `json:"max_requests_day"`
	MaxTokensDay   int64   `json:"max_tokens_day"`
	MaxCostDayUSD  float64 `json:"max_cost_day_usd"`
}

// Config is the Paperclip gates.json shape.
type Config struct {
	Version       int      `json:"version"`
	Review        Review   `json:"review"`
	HumanApproval Approval `json:"human_approval"`
	Gates         []Gate   `json:"gates"`
	GeneratedBy   string   `json:"generatedBy,omitempty"`
	GeneratedAt   string   `json:"generatedAt,omitempty"`

	// Execution options consumed by internal/gateexec (not by gates.py).
	RunnerImage         string   `json:"runner_image,omitempty"`
	Protected           []string `json:"protected,omitempty"`
	AllowPaths          []string `json:"allow_paths,omitempty"`
	DenyNewDependencies bool     `json:"deny_new_dependencies,omitempty"`
	SecretScan          bool     `json:"secret_scan,omitempty"`
	Budget              *Budget  `json:"budget,omitempty"`
}

type Review struct {
	Required   bool   `json:"required"`
	IssueMatch string `json:"issue_match,omitempty"`
}

type Approval struct {
	Required bool `json:"required"`
}

type Gate struct {
	ID         string `json:"id"`
	When       string `json:"when"`
	Command    string `json:"command"`
	Cwd        string `json:"cwd"`
	TimeoutSec int    `json:"timeout_sec"`
}

// Result reports what the last sync did; it is safe to serialise to the client.
type Result struct {
	Written       bool     `json:"written"`
	Skipped       bool     `json:"skipped"`
	Reason        string   `json:"reason,omitempty"`
	Error         string   `json:"error,omitempty"`
	Workspace     string   `json:"workspace,omitempty"`
	Path          string   `json:"path,omitempty"`
	Gates         int      `json:"gates"`
	Review        bool     `json:"review"`
	HumanApproval bool     `json:"human_approval"`
	WrittenAt     string   `json:"written_at,omitempty"`
	Hash          string   `json:"hash,omitempty"`
	Warnings      []string `json:"warnings,omitempty"`
}

// Derive builds the Paperclip config from enabled gate connectors. It never
// touches the filesystem, which makes it easy to test and preview.
func Derive(doc Document) (Config, []string) {
	cfg := Config{Version: 1, Gates: []Gate{}}
	var warnings []string
	seen := map[string]bool{}

	for _, c := range doc.Connectors {
		if !c.Enabled || c.Kind != "gate" {
			continue
		}
		var ct Contract
		if raw := strings.TrimSpace(c.Contract); raw != "" {
			if err := json.Unmarshal([]byte(raw), &ct); err != nil {
				warnings = append(warnings, fmt.Sprintf("gate %q: invalid contract: %v", c.Name, err))
				continue
			}
		}
		cfg.Review.Required = cfg.Review.Required || ct.ReviewRequired
		cfg.HumanApproval.Required = cfg.HumanApproval.Required || ct.HumanApprovalRequired
		if ct.RunnerImage != "" && cfg.RunnerImage == "" {
			cfg.RunnerImage = strings.TrimSpace(ct.RunnerImage)
		}
		cfg.Protected = mergeUnique(cfg.Protected, ct.Protected)
		cfg.AllowPaths = mergeUnique(cfg.AllowPaths, ct.AllowPaths)
		cfg.DenyNewDependencies = cfg.DenyNewDependencies || ct.DenyNewDependencies
		cfg.SecretScan = cfg.SecretScan || ct.SecretScan
		if ct.Budget != nil && cfg.Budget == nil {
			cfg.Budget = ct.Budget
		}

		command := strings.TrimSpace(ct.Command)
		if command == "" {
			continue
		}
		id := slug(c.Name)
		if id == "" {
			id = slug(c.ID)
		}
		if id == "" {
			id = fmt.Sprintf("gate-%d", len(cfg.Gates)+1)
		}
		base := id
		for n := 2; seen[id]; n++ {
			id = fmt.Sprintf("%s-%d", base, n)
		}
		seen[id] = true

		when := strings.TrimSpace(ct.When)
		if when == "" {
			when = "after_run"
		}
		cwd := strings.TrimSpace(ct.Cwd)
		if cwd == "" {
			cwd = "."
		}
		timeout := ct.TimeoutSec
		if timeout <= 0 {
			timeout = 300
		}
		cfg.Gates = append(cfg.Gates, Gate{ID: id, When: when, Command: command, Cwd: cwd, TimeoutSec: timeout})
	}

	if cfg.Review.Required && cfg.Review.IssueMatch == "" {
		cfg.Review.IssueMatch = "review"
	}
	return cfg, warnings
}

// Sync derives the config and writes it into the configured workspace. roots
// restricts where the web gateway may write (the same allowlist as the admin
// directory browser).
func Sync(raw []byte, roots []string) Result {
	var doc Document
	if err := json.Unmarshal(raw, &doc); err != nil {
		return Result{Error: "graph document is not JSON: " + err.Error()}
	}
	if doc.Paperclip == nil {
		return Result{Skipped: true, Reason: "no paperclip settings in the graph document"}
	}
	if !doc.Paperclip.enabled() {
		return Result{Skipped: true, Reason: "gate sync is disabled"}
	}
	workspace := strings.TrimSpace(doc.Paperclip.Workspace)
	if workspace == "" {
		return Result{Skipped: true, Reason: "no paperclip workspace configured"}
	}

	canonical, err := validateWorkspace(workspace, roots)
	if err != nil {
		return Result{Workspace: workspace, Error: err.Error()}
	}

	cfg, warnings := Derive(doc)
	path := filepath.Join(canonical, filepath.FromSlash(gatesRelPath))

	var existing Config
	if old, err := os.ReadFile(path); err == nil {
		_ = json.Unmarshal(old, &existing)
	}
	ownsFile := existing.GeneratedBy == GeneratedBy
	graphDerived := len(cfg.Gates) > 0 || cfg.Review.Required || cfg.HumanApproval.Required

	if !graphDerived && !ownsFile {
		return Result{
			Skipped:   true,
			Reason:    "no graph gates; existing hand-maintained config left untouched",
			Workspace: canonical,
			Path:      path,
		}
	}

	if graphDerived && !ownsFile {
		// First write over a hand-maintained file: keep gates and flags that
		// the graph does not define (e.g. a manually configured "tests" gate),
		// so turning the sync on never silently drops existing checks.
		merged := append([]Gate{}, cfg.Gates...)
		for _, old := range existing.Gates {
			if !hasGateID(cfg.Gates, old.ID) {
				merged = append(merged, old)
			}
		}
		cfg.Gates = merged
		cfg.Review.Required = cfg.Review.Required || existing.Review.Required
		cfg.HumanApproval.Required = cfg.HumanApproval.Required || existing.HumanApproval.Required
		if existing.Review.IssueMatch != "" {
			cfg.Review.IssueMatch = existing.Review.IssueMatch
		}
	}

	if cfg.Review.Required && cfg.Review.IssueMatch == "" {
		cfg.Review.IssueMatch = "review"
	}

	cfg.Version = 1
	cfg.GeneratedBy = GeneratedBy
	cfg.GeneratedAt = time.Now().UTC().Format(time.RFC3339)
	data, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return Result{Workspace: canonical, Path: path, Error: "encode gates: " + err.Error()}
	}
	data = append(data, '\n')

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return Result{Workspace: canonical, Path: path, Error: "create .paperclip: " + err.Error()}
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return Result{Workspace: canonical, Path: path, Error: "write gates: " + err.Error()}
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return Result{Workspace: canonical, Path: path, Error: "replace gates: " + err.Error()}
	}
	sum := sha256.Sum256(data)
	hash := hex.EncodeToString(sum[:])
	// Sidecar for drift detection: it records the hash of the file we wrote.
	_ = os.WriteFile(filepath.Join(filepath.Dir(path), ".gates.dockweave.json"),
		[]byte(fmt.Sprintf("{\"hash\":%q,\"generatedAt\":%q}\n", hash, cfg.GeneratedAt)), 0o644)

	return Result{
		Written:       true,
		Workspace:     canonical,
		Path:          path,
		Gates:         len(cfg.Gates),
		Review:        cfg.Review.Required,
		HumanApproval: cfg.HumanApproval.Required,
		WrittenAt:     cfg.GeneratedAt,
		Hash:          hash,
		Warnings:      warnings,
	}
}

// StatusResult reports the sync state of a workspace without changing it.
type StatusResult struct {
	Workspace   string `json:"workspace,omitempty"`
	Path        string `json:"path,omitempty"`
	Enabled     bool   `json:"enabled"`
	Exists      bool   `json:"exists"`
	Managed     bool   `json:"managed"`
	Drifted     bool   `json:"drifted"`
	Hash        string `json:"hash,omitempty"`
	GeneratedAt string `json:"generatedAt,omitempty"`
	Error       string `json:"error,omitempty"`
}

// Status compares the current gates.json with the hash written by the last
// sync, so the UI can show drift instead of silently overwriting manual edits.
func Status(raw []byte, roots []string) StatusResult {
	var doc Document
	if err := json.Unmarshal(raw, &doc); err != nil {
		return StatusResult{Error: "graph document is not JSON: " + err.Error()}
	}
	if doc.Paperclip == nil || !doc.Paperclip.enabled() {
		return StatusResult{Enabled: false}
	}
	workspace := strings.TrimSpace(doc.Paperclip.Workspace)
	if workspace == "" {
		return StatusResult{Enabled: true, Error: "no paperclip workspace configured"}
	}
	canonical, err := validateWorkspace(workspace, roots)
	if err != nil {
		return StatusResult{Enabled: true, Workspace: workspace, Error: err.Error()}
	}
	path := filepath.Join(canonical, filepath.FromSlash(gatesRelPath))
	out := StatusResult{Enabled: true, Workspace: canonical, Path: path}
	data, err := os.ReadFile(path)
	if err != nil {
		return out
	}
	out.Exists = true
	sum := sha256.Sum256(data)
	out.Hash = hex.EncodeToString(sum[:])
	var sidecar struct {
		Hash        string `json:"hash"`
		GeneratedAt string `json:"generatedAt"`
	}
	if side, err := os.ReadFile(filepath.Join(filepath.Dir(path), ".gates.dockweave.json")); err == nil {
		_ = json.Unmarshal(side, &sidecar)
	}
	var cfg Config
	_ = json.Unmarshal(data, &cfg)
	out.Managed = cfg.GeneratedBy == GeneratedBy
	out.GeneratedAt = sidecar.GeneratedAt
	out.Drifted = out.Managed && (sidecar.Hash == "" || sidecar.Hash != out.Hash)
	return out
}

// validateWorkspace canonicalises the path and enforces the allowlist. Writing
// is restricted to `<workspace>/.paperclip/gates.json`, but an arbitrary
// workspace path would still let a caller create directories anywhere.
func validateWorkspace(raw string, roots []string) (string, error) {
	if !filepath.IsAbs(raw) {
		return "", errors.New("paperclip workspace must be an absolute path")
	}
	canonical, err := filepath.EvalSymlinks(raw)
	if err != nil {
		return "", fmt.Errorf("resolve paperclip workspace: %w", err)
	}
	info, err := os.Stat(canonical)
	if err != nil {
		return "", fmt.Errorf("stat paperclip workspace: %w", err)
	}
	if !info.IsDir() {
		return "", errors.New("paperclip workspace is not a directory")
	}
	if len(roots) == 0 {
		return "", errors.New("no allowed workspace roots configured")
	}
	for _, root := range roots {
		canonRoot, err := filepath.EvalSymlinks(root)
		if err != nil {
			canonRoot = filepath.Clean(root)
		}
		rel, err := filepath.Rel(canonRoot, canonical)
		if err != nil {
			continue
		}
		if rel == "." || (rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))) {
			return canonical, nil
		}
	}
	return "", fmt.Errorf("paperclip workspace %q is outside the allowed roots", canonical)
}

func mergeUnique(dst, src []string) []string {
	seen := make(map[string]bool, len(dst)+len(src))
	out := make([]string, 0, len(dst)+len(src))
	for _, list := range [][]string{dst, src} {
		for _, v := range list {
			v = strings.TrimSpace(v)
			if v == "" || seen[v] {
				continue
			}
			seen[v] = true
			out = append(out, v)
		}
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

func hasGateID(gates []Gate, id string) bool {
	for _, g := range gates {
		if g.ID == id {
			return true
		}
	}
	return false
}

func slug(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	var b strings.Builder
	lastDash := false
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
			lastDash = false
			continue
		}
		if !lastDash && b.Len() > 0 {
			b.WriteByte('-')
			lastDash = true
		}
	}
	return strings.Trim(b.String(), "-")
}
