#!/usr/bin/env bash
# Start the bundled DockWeave Keycloak (realm import) with locally generated
# credentials and print the OIDC settings to pass to `dockweave web`.
#
#   scripts/keycloak-up.sh            # start; create missing credentials
#   scripts/keycloak-up.sh --rotate   # start; rotate admin, user and client secrets
#
# No credential is ever stored in the repository (AGENTS.md rule 9). They
# live in 0600 files under ~/.config/dockweave/:
#   keycloak.env        KC_ADMIN_USER / KC_ADMIN_PASSWORD (master realm admin)
#   keycloak-users.env  passwords of the realm users krusty, user, monitor
#   oidc.env            DOCKWEAVE_OIDC_CLIENT_SECRET for the web gateway
set -euo pipefail

ROTATE=0
case "${1:-}" in
--rotate) ROTATE=1 ;;
"") ;;
*) echo "usage: $0 [--rotate]" >&2; exit 2 ;;
esac

HERE="$(cd "$(dirname "$0")/.." && pwd)"
KC_DIR="$HERE/deployments/keycloak"
CONF="${DOCKWEAVE_CONFIG_DIR:-$HOME/.config/dockweave}"
KC_ENV="$CONF/keycloak.env"
USERS_ENV="$CONF/keycloak-users.env"
OIDC_ENV="$CONF/oidc.env"
LAN_STATE="$CONF/lan-access.env"
CTR=dockweave-keycloak
REALM_USERS=(krusty user monitor)

umask 077
mkdir -p "$CONF"

genpw() { head -c 24 /dev/urandom | base64 | tr -d '/+=\n' | head -c 28; }

# write_env FILE KEY=VALUE... — atomic, 0600, never echoed.
write_env() {
	local f="$1"; shift
	printf '%s\n' "$@" >"$f.tmp"
	chmod 600 "$f.tmp"
	mv "$f.tmp" "$f"
}

# kc CMD... — kcadm inside the container. Secrets are passed on stdin as
# $SECRET, never on the host command line.
kc() { docker exec -i "$CTR" /opt/keycloak/bin/kcadm.sh "$@"; }
kc_secret() { # $1 = secret, rest = shell snippet using "$SECRET"
	local secret="$1"; shift
	printf '%s\n' "$secret" | docker exec -i "$CTR" sh -c 'IFS= read -r SECRET; '"$*"
}
kc_login() { # $1 = admin password
	kc_secret "$1" '/opt/keycloak/bin/kcadm.sh config credentials --server http://localhost:8080 --realm master --user "$KC_BOOTSTRAP_ADMIN_USERNAME" --password "$SECRET" >/dev/null'
}

compose_up() {
	local files=(-f docker-compose.yml)
	if [ -f "$LAN_STATE" ]; then
		# LAN access is on: keep the TLS issuer (scripts/lan-access.sh).
		# shellcheck disable=SC1090
		. "$LAN_STATE"
		export LAN_HOST
		files+=(-f docker-compose.lan.yml)
	fi
	(cd "$KC_DIR" && docker compose "${files[@]}" up -d --wait)
}

# 1) Master-realm admin password.
OLD_ADMIN_PW=""
if [ -f "$KC_ENV" ]; then
	# shellcheck disable=SC1090
	. "$KC_ENV"
fi
if docker ps --format '{{.Names}}' | grep -qx "$CTR"; then
	# The running container's bootstrap env is what kcadm can log in with.
	OLD_ADMIN_PW="$(docker exec "$CTR" printenv KC_BOOTSTRAP_ADMIN_PASSWORD 2>/dev/null || true)"
fi
export KC_ADMIN_USER="${KC_ADMIN_USER:-admin}"
if [ -z "${KC_ADMIN_PASSWORD:-}" ] || [ "$ROTATE" = 1 ]; then
	NEW_ADMIN_PW="$(genpw)"
	if [ -n "$OLD_ADMIN_PW" ]; then
		echo "==> Rotating the Keycloak master admin password"
		kc_login "$OLD_ADMIN_PW"
		kc_secret "$NEW_ADMIN_PW" '/opt/keycloak/bin/kcadm.sh set-password -r master --username "$KC_BOOTSTRAP_ADMIN_USERNAME" --new-password "$SECRET"'
	fi
	KC_ADMIN_PASSWORD="$NEW_ADMIN_PW"
	write_env "$KC_ENV" "KC_ADMIN_USER=$KC_ADMIN_USER" "KC_ADMIN_PASSWORD=$KC_ADMIN_PASSWORD"
fi
export KC_ADMIN_PASSWORD

# 2) Start (or recreate with the current env and loopback-only port).
compose_up
if ! kc_login "$KC_ADMIN_PASSWORD"; then
	echo "error: cannot log in as the Keycloak master admin with $KC_ENV." >&2
	echo "       The keycloak-data volume may still hold an older password: set it in" >&2
	echo "       KC_ADMIN_PASSWORD there (or reset the volume) and run again." >&2
	exit 1
fi

# 3) Realm users: random passwords, created on first run or on --rotate.
if [ ! -f "$USERS_ENV" ] || [ "$ROTATE" = 1 ]; then
	echo "==> Setting random passwords for realm users: ${REALM_USERS[*]}"
	lines=()
	for u in "${REALM_USERS[@]}"; do
		pw="$(genpw)"
		kc_secret "$pw" "/opt/keycloak/bin/kcadm.sh set-password -r dockweave --username $u --new-password \"\$SECRET\""
		lines+=("KC_USER_$(printf '%s' "$u" | tr '[:lower:]' '[:upper:]')_PASSWORD=$pw")
	done
	write_env "$USERS_ENV" "${lines[@]}"
fi

# 4) Client: no password grant; secret generated by Keycloak, stored locally.
CID="$(kc get clients -r dockweave -q clientId=dockweave --fields id | python3 -c 'import json,sys; print(json.load(sys.stdin)[0]["id"])')"
kc update "clients/$CID" -r dockweave -s directAccessGrantsEnabled=false >/dev/null
if [ ! -f "$OIDC_ENV" ] || [ "$ROTATE" = 1 ]; then
	echo "==> Generating a new OIDC client secret"
	kc create "clients/$CID/client-secret" -r dockweave >/dev/null
	SECRET="$(kc get "clients/$CID/client-secret" -r dockweave | python3 -c 'import json,sys; print(json.load(sys.stdin)["value"])')"
	write_env "$OIDC_ENV" "DOCKWEAVE_OIDC_CLIENT_SECRET=$SECRET"
	unset SECRET
fi

ISSUER="http://127.0.0.1:${KEYCLOAK_PORT:-8080}/realms/dockweave"
[ -f "$LAN_STATE" ] && ISSUER="https://$LAN_HOST:8444/realms/dockweave"
cat <<EOF

Keycloak läuft (nur 127.0.0.1:${KEYCLOAK_PORT:-8080}). Issuer: $ISSUER

Zugangsdaten (nur lokal, 0600):
  $KC_ENV        Master-Admin (Admin-Konsole http://127.0.0.1:${KEYCLOAK_PORT:-8080}/admin)
  $USERS_ENV  Passwörter für ${REALM_USERS[*]}
  $OIDC_ENV            Client-Secret für das Gateway

dockweave web mit OIDC starten:

  set -a; . $OIDC_ENV; set +a
  DOCKWEAVE_OIDC_ISSUER=$ISSUER \\
  DOCKWEAVE_OIDC_CLIENT_ID=dockweave \\
  DOCKWEAVE_OIDC_ADMIN_GROUPS=dockweave-admin \\
  DOCKWEAVE_OIDC_MONITOR_GROUPS=dockweave-monitor \\
  dockweave web --listen 127.0.0.1:8790

Als systemd-User-Unit: EnvironmentFile=-%h/.config/dockweave/oidc.env
Benutzer: krusty (dockweave-admin) · user (Standard) · monitor (dockweave-monitor)
EOF
